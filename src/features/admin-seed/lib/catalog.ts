export function topicId(programId: string, topicIndex: number): string {
	return `${programId}:topic:${topicIndex}`;
}

export function lessonId(
	programId: string,
	topicIndex: number,
	lessonIndex: number,
): string {
	return `${programId}:lesson:${topicIndex}:${lessonIndex}`;
}

export function activityId(
	lessonKey: string,
	type: "theory" | "practice",
): string {
	return `${lessonKey}:activity:${type}`;
}

/** Test group id backing a lesson's practice activity. */
export function testGroupId(lessonKey: string): string {
	return `${lessonKey}:test-group`;
}
